#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Чесна числова перевірка з урахуванням ЗМІННОЇ обвідної синуса (0 -> пік -> 0 кожні 10 мс).
Ніяких "розрахунків по піку" - все інтегрується по періоду 50 Гц.
"""
import math

RHO20, ALPHA, MU0 = 1.72e-8, 0.00393, 4*math.pi*1e-7
rho = lambda T: RHO20*(1+ALPHA*(T-20))
delta = lambda f, T=100: math.sqrt(rho(T)/(math.pi*f*MU0))

def dowell(h, d, m):
    D = h/d
    return (D*(math.sinh(2*D)+math.sin(2*D))/(math.cosh(2*D)-math.cos(2*D))
            + (2/3)*D*(m*m-1)*(math.sinh(D)-math.sin(D))/(math.cosh(D)+math.cos(D)))

def hr(t): print("\n"+"="*78+"\n"+t+"\n"+"="*78)

P, Vo = 3000.0, 230.0
Vpk = Vo*math.sqrt(2); Io_rms = P/Vo; Io_pk = Io_rms*math.sqrt(2)

# ---------------------------------------------------------------------------
hr("1. ЧИ Я РАХУВАВ 'ПО ПІКУ'? - числове інтегрування по періоду 50 Гц")

N = 200000
Vbat, d_max = 24.0, 0.90
n = Vpk/(Vbat*d_max)

s_i2_pri = s_i2_sec = s_ibat = s_ibat2 = s_b26 = 0.0
for k in range(N):
    th = math.pi*(k+0.5)/N               # півперіод достатньо (симетрія)
    d = d_max*math.sin(th)               # duty у цей момент
    i_pri_on = n*Io_pk*math.sin(th)      # струм первинки ПІД ЧАС провідності
    s_i2_pri += d*i_pri_on**2            # RMS^2 з урахуванням, що поза duty струму нема
    s_i2_sec += d*(Io_pk*math.sin(th))**2
    s_ibat   += d*i_pri_on
    s_ibat2  += d*i_pri_on**2
    s_b26    += math.sin(th)**2.6        # для середніх втрат у фериті (Steinmetz b=2.6)
I_pri_rms = math.sqrt(s_i2_pri/N); I_sec_rms = math.sqrt(s_i2_sec/N)
I_bat_avg = s_ibat/N; I_bat_rms = math.sqrt(s_ibat2/N); k_core = s_b26/N

print(f"Vbat={Vbat} В, n={n:.1f}, duty на піку={d_max}")
print(f"  I первинки: ПІК під час провідності = {n*Io_pk:.0f} А")
print(f"  I первинки: RMS за весь період 50 Гц = {I_pri_rms:.1f} А   <-- саме це я брав у втрати")
print(f"  Якби рахував 'по піку' (постійні {n*Io_pk:.0f} А), вийшло б у "
      f"{(n*Io_pk/I_pri_rms)**2:.1f} рази більше втрат.")
print(f"  I батареї: avg={I_bat_avg:.0f} А, RMS={I_bat_rms:.0f} А")
print(f"  Коеф. усереднення втрат у фериті через змінну обвідну: x{k_core:.2f}")
print("\nВИСНОВОК: так, обвідна 0->пік->0 ВЖЕ врахована. Втрати 52-75 Вт на LV-мості -")
print("це середні за період, а не миттєві на піку. Миттєві на піку синуса втричі більші.")

# ---------------------------------------------------------------------------
hr("2. ЧИ ВИТРИМАЮТЬ IRLB3034 ПО СТРУМУ? - так. Але це не про струм, а про Вт")
RDS_HOT = 0.0017*1.55
for m in (2, 3, 4):
    i_pk_dev = n*Io_pk/m
    Pcond = I_pri_rms**2 * 2*(RDS_HOT/m)
    per_dev = Pcond/(4*m)
    Tj = per_dev*(0.4+0.5)+80          # Rth j-c 0.4 + прокладка/радіатор ~0.5, база 80 C
    print(f"  {m}/плече: пік на ключ {i_pk_dev:5.0f} А з 380 А допустимих -> "
          f"{'ОК ' if i_pk_dev<380 else 'НЕ ОК'}  | середні {per_dev:4.1f} Вт/ключ, "
          f"Tj~{Tj:.0f} C | ВСЬОГО МІСТ {Pcond:5.1f} Вт = {Pcond/P*100:.2f}% ККД")
print("\n  Ти правий: по струму запас є, ключі не згорять. Проблема інша -")
print("  ці ватти віднімаються від ККД. 52 Вт на 3 кВт = 1.7% тільки LV-міст.")

hr("3. СКІЛЬКИ MOSFET ПОТРІБНО, ЩОБ ККД БУВ 99%? (бюджет усього 30 Вт)")
for target in (10.0, 5.0):
    m_req = I_pri_rms**2*2*RDS_HOT/target
    print(f"  Щоб LV-міст мав лише {target:.0f} Вт: потрібно {m_req:.0f} шт IRLB3034 на плече "
          f"= {4*m_req:.0f} шт на міст")
print("  Плюс HV-каскад (нижче) сам по собі забирає ~28 Вт.")
print("  Тобто 99% (=30 Вт) фізично не залишає місця ні на що інше. Це і є відповідь.")

# ---------------------------------------------------------------------------
hr("4. 'HV МОСТА НЕМА, Є ІДЕАЛЬНИЙ ДІОД' - розбір, і ти маєш рацію на 80%")
RDS_HV = 0.019*2.2
print("Твоя ідея у чистому вигляді розкладається на ДВІ функції, і це важливо:")
print("  A) синхронний випрямляч (SR) на 150 кГц - це і є твій 'ідеальний діод'.")
print("     Струм тут ОДНОНАПРАВЛЕНИЙ -> body diode не мішає -> звичайні MOSFET ОК.")
print("  B) розгортка полярності (unfolder) - перемикається на переходах синуса,")
print("     тобто справді 50 Гц, при напрузі ~0 -> комутаційні втрати ~0.")
print("\n  Якщо ти маєш на увазі саме A+B - твоє твердження ПРАВИЛЬНЕ, і мій закид")
print("  про '4-квадрантні ключі + 150 кГц комутація' стосується іншого варіанту:")
print("  коли один і той самий міст робить обидві функції одночасно (циклоконвертор).")
print("\n  АЛЕ по мідяних втратах різниці майже немає - рахуємо шлях струму:")
for label, ndev in (("SR (2 ключі) + unfolder (2 ключі)", 4),
                    ("циклоконвертор з 4-кв. ключами", 4),
                    ("SR з середньою точкою (1) + unfolder (2)", 3),
                    ("тільки SR, без unfolder (дає |sin|, не синус!)", 2)):
    print(f"    {label:<45s} {ndev} шт у шляху -> "
          f"{Io_rms**2*ndev*RDS_HV:5.1f} Вт")
print(f"  (Rds(on) 19 мОм @25C -> {RDS_HV*1e3:.0f} мОм гарячий - це головний фактор)")
print("\n  Тобто HV-каскад = 21-28 Вт майже за будь-якої архітектури.")
print("  Щоб зменшити: паралелити по 2 ключі (14 Вт) або SR із середньою точкою.")
print("\n  Що реально треба вирішити для 'ідеального діода' на 150 кГц:")
print("   - вікно провідності SR змінюється щоцикла (duty біжить по синусу + leakage),")
print("     тому вмикати його по фіксованому таймеру з ESP32 небезпечно: вмикання при")
print("     зворотній напрузі = коротке через трансформатор.")
print("   - серійно це роблять аналогово: датчик Vds + компаратор на кожен ключ")
print("     (як у SR-контролерів). ESP32 задає тільки грубе вікно.")
print("   - phase shift керує ПЕРЕДАЧЕЮ ЕНЕРГІЇ (LV-міст), а не моментом SR.")

# ---------------------------------------------------------------------------
hr("5. ТРАНСФОРМАТОР - повний чесний розрахунок")
Ae, Ve, MLT = 368e-6, 51.5e-6, 0.106
bw, hw = 38e-3, 9.5e-3          # вікно намотки ETD59 (перевірити по даталисту каркаса)
Aw = bw*hw
print(f"ETD59/31/22: Ae={Ae*1e6:.0f} мм², Ve={Ve*1e6:.1f} см³, вікно {bw*1e3:.0f}x{hw*1e3:.1f} мм "
      f"= {Aw*1e6:.0f} мм² на секцію")

def core_loss(B, f, C=39.4, a=1.35, b=2.6):
    return C*(f/1e3)**a*B**b*(Ve*1e6)/1e3

def design_tx(f_sw, Np, n_par, sec_type, Ns=None, A_sec=None, m_sec=1, T=100):
    d = delta(f_sw, T)
    Ns = Ns or round(n*Np)
    B = Vbat*d_max/(4*f_sw*Np*Ae)
    Pc = core_loss(B, f_sw)*k_core
    h = 0.2e-3
    A_p = h*bw*n_par
    R_p = rho(T)*MLT*Np/A_p
    Fr_p = dowell(h, d, max(1, n_par//2))
    Pp = I_pri_rms**2*R_p*Fr_p
    R_s = rho(T)*MLT*Ns/A_sec
    if sec_type == "foil":
        Fr_s = dowell(h, d, m_sec)
    else:
        Fr_s = 1.15
    Ps = I_sec_rms**2*R_s*Fr_s
    return dict(f=f_sw, d=d, Np=Np, Ns=Ns, B=B, Pc=Pc, Pp=Pp, Ps=Ps, Fr_p=Fr_p, Fr_s=Fr_s,
                tot=Pc+Pp+Ps, A_p=A_p)

print("\nВАРІАНТИ (Np=1, 4 шари фольги 0.2x38 мм ПАРАЛЕЛЬНО = 30.4 мм²):")
rows = [
    ("150 кГц, вторинка фольгою 18 шарів", design_tx(150e3, 1, 4, "foil", A_sec=0.2e-3*bw, m_sec=9)),
    ("150 кГц, вторинка літц 2.5 мм²",     design_tx(150e3, 1, 4, "litz", A_sec=2.5e-6)),
    ("150 кГц, вторинка літц 5 мм²",       design_tx(150e3, 1, 4, "litz", A_sec=5e-6)),
    (" 70 кГц, вторинка літц 5 мм²",       design_tx(70e3, 1, 4, "litz", A_sec=5e-6)),
    (" 70 кГц, Np=2, літц 5 мм²",          design_tx(70e3, 2, 4, "litz", A_sec=5e-6)),
]
for lbl, r in rows:
    print(f"  {lbl:<38s} Ns={r['Ns']:>2d} B={r['B']*1e3:3.0f}мТл  "
          f"ферит={r['Pc']:4.1f}  перв={r['Pp']:4.1f}(Fr={r['Fr_p']:.2f})  "
          f"втор={r['Ps']:5.1f}(Fr={r['Fr_s']:5.2f})  РАЗОМ={r['tot']:5.1f} Вт")

print("\n  УВАГА на рядок 1: 18 витків вторинки фольгою = 9 шарів у секції -> Fr≈10.")
print("  Тобто 'мотаємо все фольгою' для вторинки НЕ працює. Вторинка = літцендрат.")

hr("6. ТЕПЛО САМОГО ТРАНСФОРМАТОРА - те, що завжди забувають")
Rth_tx = 8.0    # K/W для ETD59 у природній конвекції
for Pt in (7, 10, 13):
    print(f"  {Pt} Вт у ETD59: природна конвекція (Rth~{Rth_tx:.0f} K/Вт) -> "
          f"+{Pt*Rth_tx:.0f} °C -> обмотка {40+Pt*Rth_tx:.0f} °C "
          f"| з обдувом 2 м/с (Rth~{Rth_tx/2.5:.1f}) -> +{Pt*Rth_tx/2.5:.0f} °C")
print("  Тобто навіть 'красиві' 7-10 Вт у ETD59 БЕЗ обдуву = 95-120 °C на обмотці.")
print("  Ізоляція класу B/F це витримає, але 'холодний трансформатор' - міф.")

hr("7. LEAKAGE З УРАХУВАННЯМ ОБВІДНОЇ (усереднено, не по піку)")
Ipk_pri = n*Io_pk
for f_sw in (150e3, 70e3):
    for Llk in (10e-9, 20e-9):
        # середня енергія за період: 0.5*L*I^2 усереднено по sin^2 -> x0.5
        Pl = 0.5*Llk*Ipk_pri**2*0.5*2*f_sw
        tloss = Llk*Ipk_pri/Vbat/(1/(2*f_sw))
        print(f"  f={f_sw/1e3:3.0f} кГц, Llk={Llk*1e9:2.0f} нГн: втрата duty на піку "
              f"{tloss*100:4.1f}%,  енергія розсіювання (жорстко) = {Pl:5.0f} Вт сер.")
print("  Це не 'обов'язкові' втрати - але саме цю енергію ZVS/ZVT мусить повернути.")
print("  На 70 кГц вимоги до м'якої комутації вдвічі мʼякші. Ось чому я радив опустити частоту.")

hr("8. ІТОГО, ЧЕСНО, 24 В / 3 кВт, оптимістичний але реальний варіант")
items = [("LV міст 4/плече (провідникові)", I_pri_rms**2*2*(RDS_HOT/4)),
         ("LV затвори (16 шт, 150 кГц)", 2*4*2*210e-9*10*150e3),
         ("LV перемикальні біля нуля синуса", 6.0),
         ("Трансформатор (літц вторинка, 150 кГц)", 12.0),
         ("HV: SR + unfolder, 4 ключі в шляху", Io_rms**2*4*RDS_HV),
         ("HV перемикальні (SR на 150 кГц)", 10.0),
         ("Вихідний LC-фільтр", 12.0),
         ("Вхідні конденсатори + шини + клеми", 10.0),
         ("Драйвери, ESP32, вентилятор, вимірювання", 6.0)]
tot = sum(v for _, v in items)
for k, v in items: print(f"    {k:<42s} {v:6.1f} Вт")
print(f"    {'РАЗОМ':<42s} {tot:6.1f} Вт  ->  ККД = {P/(P+tot)*100:.2f}%")
print(f"\n  А на 1.5 кВт (половина потужності) той самий блок: ", end="")
tot_half = (items[0][1]+items[4][1]+items[3][1]*0.6+items[6][1]*0.5)/4 + sum(v for _, v in items[1:3]) + items[5][1]*0.5 + items[7][1]/4 + items[8][1]
print(f"~{tot_half:.0f} Вт -> ККД = {1500/(1500+tot_half)*100:.2f}%")
print("  (на малій потужності ККД дійсно вище - тут ти теж мав рацію)")
