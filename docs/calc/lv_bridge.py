#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ПОВНЕ ОБҐРУНТУВАННЯ ВТРАТ LV-МОСТА
IRLB3034 x m паралельно в плечі, phase-shift full bridge, драйвер FAN7390
Кожна складова виводиться з формули + даталистних даних, а не з оцінки "на око".

Ключ: IRL40SC209 (StrongIRFET, 40 В, D2PAK-7 з ОКРЕМИМ Kelvin source).
Rds(on) = 0.59 мОм typ / 0.72 мОм max @ Vgs=10 В (кристал "209", як у IRL40T209).
Оцінки, які треба звірити з даталистом (позначено *):
  Rth(j-c) ~ 0.55 K/Вт* ; Qg @ Vgs=12 В ~ 500 нК* ; Coss ~ 8.0 нФ* ; Crss ~ 2.0 нФ*
  (Qg і Coss масштабовані під великий кристал 0.6 мОм - вони приблизно вдвічі більші,
   ніж у 1.3-мОм ключа, і це прямо піднімає постійні втрати)
  Vf body diode ~ 0.9 В*
Тепловий шлях D2PAK-7 іде через плату -> rth_pad = 1.2 K/Вт* (IMS / теплові вії),
на відміну від TO-220, притягнутого до радіатора винтом (0.7 K/Вт).
"""
import math

def hr(t): print("\n"+"="*80+"\n"+t+"\n"+"="*80)

# ---------------- вхідні дані режиму
P, Vo = 3000.0, 230.0
Vpk = Vo*math.sqrt(2); Io_rms = P/Vo; Io_pk = Io_rms*math.sqrt(2)
Vbat, d_max, f_c = 24.0, 0.90, 150e3
VBAT_MIN = 20.0
# n задає МІНІМАЛЬНА напруга пака, а не номінал: залізо фіксоване, тому струм
# первинки n*Iout НЕ залежить від рівня заряду. Vbat нижче використовується тільки
# там, де важлива фактична напруга шини (dv/dt, ZVS, викиди).
n = Vpk/(VBAT_MIN*d_max)
I_pri_rms = n*Io_rms          # варіант 1: freewheel через SR -> струм циркулює
I_pri_pk  = n*Io_pk

# ---------------- даталист / оцінки
RDS25_MAX = 0.00072
RTH_JC    = 0.55
QG_12V    = 250e-9      # *оцінка
COSS_ER   = 3.0e-9      # *оцінка
CRSS      = 0.8e-9      # *оцінка
VF_DIODE  = 0.90        # *оцінка
VDD_GATE  = 12.0
L_SRC_TO220 = 7e-9      # індуктивність виводу джерела TO-220
L_LK      = 15e-9       # розсіювання трансформатора, приведене до первинки

hr("1. РЕЖИМ")
print(f"  Pout={P:.0f} Вт, Vout={Vo:.0f} В RMS, Iout={Io_rms:.2f} А RMS / {Io_pk:.1f} А пік")
print(f"  Vbat={Vbat:.0f} В, duty на піку синуса={d_max}, n={n:.1f}")
print(f"  I первинки: RMS={I_pri_rms:.1f} А, пік={I_pri_pk:.1f} А")
print(f"  Носій {f_c/1e3:.0f} кГц -> період {1/f_c*1e6:.2f} мкс, напівперіод {1/(2*f_c)*1e6:.2f} мкс")

hr("2. ПРОВІДНИКОВІ ВТРАТИ: чому 'два ключі в шляху' і скільки на кожен")
print("Стани phase-shift full bridge (плече A - ведуче, B - ведене):")
print("   передача '+' : A1 + B2 увімкнені      -> 2 ключі в шляху")
print("   freewheel    : A1 + B1 (верхній)      -> 2 ключі в шляху")
print("   передача '-' : A2 + B1                -> 2 ключі в шляху")
print("   freewheel    : A2 + B2 (нижній)       -> 2 ключі в шляху")
print("Тобто В КОЖЕН момент проводять рівно 2 ключі, і кожен з 4 позицій - 50% часу.")
print("  P_моста = I_rms^2 * 2 * Rds/m        (m - паралельних на плече)")
print("  P_на_ключ = 0.5 * I_rms^2 * Rds/m^2   (він несе I/m і лише 50% часу)")
print()
print("Тепер ІТЕРАЦІЙНО: Rds залежить від Tj, а Tj від втрат. Розвʼязую самоузгоджено.")
print("Температурний коеф. IRLB3034: беру Rds(Tj)=Rds25*(1+0.0060*(Tj-25)) -> x1.60 при 125°C")

def solve_leg(m, T_hs=70.0, Rth_pad=1.2, verbose=True):
    """T_hs - температура радіатора, Rth_pad - прокладка+термопаста на ключ"""
    Tj = T_hs + 20
    for _ in range(200):
        rds = RDS25_MAX*(1+0.0060*(Tj-25))
        P_tot = I_pri_rms**2*2*(rds/m)
        P_dev = P_tot/(4*m)
        Tj_new = T_hs + P_dev*(RTH_JC+Rth_pad)
        if abs(Tj_new-Tj) < 0.01: break
        Tj = 0.5*Tj+0.5*Tj_new
    if verbose:
        print(f"  m={m}: Rds(гарячий)={rds*1e3:.2f} мОм  Tj={Tj:.0f}°C  "
              f"P_на_ключ={P_dev:5.2f} Вт  P_МОСТА={P_tot:6.1f} Вт  ({P_tot/P*100:.2f}% від 3 кВт)")
    return P_tot, P_dev, Tj, rds

print()
res = {}
for m in (2, 3, 4):
    res[m] = solve_leg(m)
print()
print("  Пік струму на один ключ:")
for m in (2, 3, 4):
    print(f"    m={m}: {I_pri_pk/m:5.1f} А з 195 А (обмеження корпусу) -> запас x{195/(I_pri_pk/m):.1f}")

hr("3. ЗАТВОРИ: скільки треба і чи витягне FAN7390")
print("FAN7390 (onsemi): високо/низьковольтний драйвер напівмоста, 600 В, bootstrap,")
print("заявлена висока пікова здатність виходу (за даталистом ~4.5 А, звір по таблиці).")
print()
for m in (2, 3):
    Qg_leg = m*QG_12V
    P_gate_total = 4*m*QG_12V*VDD_GATE*f_c        # весь міст (4 позиції)
    P_per_channel = m*QG_12V*VDD_GATE*f_c          # на один канал драйвера
    t_min = Qg_leg/4.5
    print(f"  m={m}: Qg на канал = {Qg_leg*1e9:.0f} нК")
    print(f"        мінімальний час перемикання при 4.5 А = {t_min*1e9:.0f} нс "
          f"(це {t_min/(1/f_c)*100:.1f}% періоду)")
    print(f"        потужність у контурі затвора: {P_per_channel:.2f} Вт на канал, "
          f"{P_gate_total:.2f} Вт на весь міст")
    print(f"        FAN7390 у SO-8/SO-14 має Rth(JA)~100 K/Вт -> "
          f"{P_per_channel*2*100:.0f} °C перегріву, якщо вся ця потужність осідає в ІС")
print()
print("  ВИСНОВОК ПО ДРАЙВЕРУ:")
print("   - 1 шт FAN7390 на плече з 3 IRLB3034 при 150 кГц НЕ ПРОХОДИТЬ по тепловіддачі ІС.")
print("   - Треба або зовнішні бустери (пара NPN/PNP чи окремий драйвер на кожен MOSFET),")
print("     або великі індивідуальні Rg (щоб тепло сідало в резистори, а не в ІС),")
print("     або нижча частота носія.")
print("   - Індивідуальний Rg на кожен MOSFET обовʼязковий також для розподілу струму")
print("     і проти паразитних коливань між паралельними ключами.")
print()
Cboot_min = 3*QG_12V/0.5
print(f"  Bootstrap: заряд на цикл {3*QG_12V*1e9:.0f} нК (m=3) при просіданні 0.5 В ->")
print(f"    Cboot >= {Cboot_min*1e6:.1f} мкФ, практично 4.7-10 мкФ + швидкий діод на "
      f"{3*QG_12V*f_c*1e3:.0f} мА середнього струму")
print("  Ключова перевага фазового зсуву: кожен ключ має duty ~50% на носії, тому")
print("  bootstrap перезаряджається щоцикла - тут проблем немає (на відміну від")
print("  класичного PWM, де верхній ключ може висіти відкритим довго).")

hr("4. ФАЗОВИЙ ЗСУВ І ZVS: чи справді верхній ключ перемикається при нулі напруги")
Cnode = 2*3*COSS_ER      # два ключі плеча x m=3
print(f"Ємність вузла плеча (m=3): 2 x 3 x Coss = {Cnode*1e9:.1f} нФ")
print(f"Індуктивність, що качає ZVS: розсіювання Llk = {L_LK*1e9:.0f} нГн (+ магнітна)")
I_zvs = Vbat*math.sqrt(Cnode/L_LK)
print(f"\nУмова ZVS: 0.5*L*I^2 >= 0.5*C*V^2  ->  I_min = V*sqrt(C/L) = {I_zvs:.1f} А по первинці")
i_out_thr = I_zvs/n
theta = math.degrees(math.asin(min(1, i_out_thr/Io_pk)))
frac = theta/90
print(f"  {I_zvs:.1f} А первинки = {i_out_thr:.2f} А на виході = кут {theta:.1f}° синуса")
print(f"  Отже ZVS втрачається лише у {frac*100:.1f}% кожної півхвилі (біля нуля синуса).")
E_hard = 0.5*Cnode*Vbat**2
P_hard = E_hard*2*2*f_c*frac    # 2 плеча x 2 переходи за період
print(f"  Втрати жорсткого перемикання в цьому вікні: E=0.5*C*V^2={E_hard*1e6:.1f} мкДж, "
      f"P={P_hard:.2f} Вт")
print("  ТОБТО: ZVS у цій схемі виходить майже 'сам собою' - струм величезний,")
print("  енергії на перезаряд Coss удосталь. Тут твоя ідея працює.")
print()
print("АЛЕ Є ЗВОРОТНА ПРОБЛЕМА, про яку ніхто не думає:")
dvdt = I_pri_pk/Cnode
print(f"  На піку синуса струм {I_pri_pk:.0f} А перезаряджає {Cnode*1e9:.1f} нФ за "
      f"{Cnode*Vbat/I_pri_pk*1e9:.2f} нс -> dv/dt = {dvdt/1e9:.1f} В/нс")
i_miller = 3*CRSS*dvdt
print(f"  Через Crss (3 x {CRSS*1e12:.0f} пФ) у затвор закритого ключа вливається "
      f"i = Crss*dv/dt = {i_miller:.0f} А (!)")
print("  Жоден драйвер це не втримає -> ключ частково відкривається (Miller turn-on).")
print("  Лікується: (а) відʼємна напруга -5 В у закритому стані, (б) снабер-конденсатор")
print("  на плече, щоб штучно уповільнити dv/dt, (в) сильний сінк на затворі.")
C_snub = I_pri_pk/2e9
print(f"  Щоб отримати помірні 2 В/нс, треба довести ємність вузла до "
      f"{C_snub*1e9:.0f} нФ (тобто +{(C_snub-Cnode)*1e9:.0f} нФ снабера).")
print("  У ZVS ця енергія повертається в джерело, тому це не прямі втрати -")
print("  але це серйозна схемотехніка, а не 'ESP32 сам підбере таймінг'.")

hr("5. МЕРТВИЙ ЧАС: провідність body diode")
for t_dt in (100e-9, 200e-9):
    # 2 переходи за період; в кожному діод одного плеча проводить t_dt
    # струм ~ I(t), середнє по синусу = (2/pi)*Ipk
    I_avg_sin = (2/math.pi)*I_pri_pk
    Pd = VF_DIODE*I_avg_sin*(t_dt*2*f_c)*2   # 2 плеча
    print(f"  Мертвий час {t_dt*1e9:.0f} нс: P = Vf*I_сер*(2*t_dt*f)*2плеча = {Pd:5.1f} Вт")
print("  Це реальні втрати, яких у 'ідеальному ZVS' начебто немає. Мінімізуються")
print("  коротким мертвим часом (12.5 нс крок ESP32 тут достатній) і синхронним")
print("  увімкненням каналу відразу після перезаряду Coss.")

hr("6. ІНДУКТИВНІСТЬ ВИВОДУ: чому Kelvin source у D2PAK-7 знімає цю проблему")
print("Раніше я порахував викид, ніби весь струм комутує один ключ. Це неправильно:")
for m in (2, 3, 4):
    for t_off in (50e-9, 100e-9):
        didt = (I_pri_pk/m)/t_off
        print(f"  m={m}, вимкнення за {t_off*1e9:.0f} нс: di/dt на ключ = {didt/1e9:.2f} А/нс "
              f"-> на 7 нГн виводу джерела = {L_SRC_TO220*didt:.1f} В")
print("  Тобто при 3-4 паралельних і мʼякому вимиканні це 3-7 В, а не 23 В, як я писав.")
print("  Це вже терпимо, але саме тому потрібні: індивідуальні Rg, симетрична розводка,")
print("  і бажано відʼємне зміщення затвора.")
print("  IRL40SC209 у D2PAK-7 має ОКРЕМИЙ Kelvin source -> цієї наводки в затворному")
print("  контурі просто немає, за умови що затвор замикається саме на цей вивід.")
print("  Наведені вище цифри стосуються TO-220 і потрібні лише для порівняння.")

hr("7. ЗВЕДЕНИЙ БЮДЖЕТ LV-ЧАСТИНИ (24 В, 3 кВт, 150 кГц)")
for m in (2, 3):
    P_cond, P_dev, Tj, rds = solve_leg(m, verbose=False)
    P_gate = 4*m*QG_12V*VDD_GATE*f_c
    I_avg_sin = (2/math.pi)*I_pri_pk
    P_dt = VF_DIODE*I_avg_sin*(100e-9*2*f_c)*2
    Cnode_m = 2*m*COSS_ER
    I_zvs_m = Vbat*math.sqrt(Cnode_m/L_LK)
    frac_m = math.degrees(math.asin(min(1, I_zvs_m/n/Io_pk)))/90
    P_hs = 0.5*Cnode_m*Vbat**2*4*f_c*frac_m
    P_coss_hyst = 1.0
    P_int = I_pri_rms**2*0.30e-3      # шини/паяні зʼєднання/виводи первинного контуру
    items = [("Провідникові у кристалах", P_cond),
             ("Шини і зʼєднання (0.30 мОм)", P_int),
             ("Контур затворів (Qg*Vdd*f, 4 позиції)", P_gate),
             ("Body diode у мертвий час (100 нс)", P_dt),
             ("Жорстке перемикання біля нуля синуса", P_hs),
             ("Гістерезис Coss + інше", P_coss_hyst)]
    tot = sum(v for _, v in items)
    print(f"\n  --- m={m} ({4*m} шт IRL40SC209), Tj={Tj:.0f}°C, {P_dev:.1f} Вт на ключ ---")
    for k, v in items: print(f"    {k:<42s} {v:6.2f} Вт")
    print(f"    {'РАЗОМ LV':<42s} {tot:6.2f} Вт  = {tot/P*100:.2f}% від 3 кВт")

hr("8. ЩО ДАЄ ПЕРЕХІД НА 48 В ПРИ ТІЙ САМІЙ СХЕМІ")
for Vb, Vb_min in ((24.0, 20.0), (48.0, 40.0)):
    n_ = Vpk/(Vb_min*d_max); I_ = n_*Io_rms
    for m in (3,):
        rds = RDS25_MAX*1.5
        print(f"  Vbat={Vb:.0f} В: n={n_:4.1f}, I_pri={I_:5.1f} А -> провідникові "
              f"{I_**2*2*rds/m:6.1f} Вт (m={m})")
print("  Квадратична залежність: удвічі вища напруга = вчетверо менші втрати.")
print("  Але IRL40SC209 має 40 В: для 48-вольтової шини (13s max 54.6 В) потрібен")
print("  аналог на 80-100 В у такому ж корпусі з Kelvin source.")
