def budget(Vbat, m_lv, label):
    n, d, Ipk, Irms, Isec = design(Vbat)
    lv_cond = Irms**2 * 2 * (RDS_LV_HOT / m_lv)
    lv_gate = 2 * m_lv * 2 * QG_LV * 10.0 * f
    lv_sw = 8.0 if Vbat <= 24 else 6.0        # часткове жорстке перемикання біля нуля синуса, Coss
    tx_cu = Irms**2 * (rho_cu(100)*MLT/(30.4e-6)) * 1.44 + 1.7
    tx_core = 2.0
    hv_cond = Iout_rms**2 * 4 * RDS_HV_HOT
    hv_sw = 20.0
    filt = 15.0
    caps_bus = 12.0
    aux = 7.0
    items = [("LV міст (провідникові)", lv_cond), ("LV затвори", lv_gate),
             ("LV перемикальні/Coss", lv_sw), ("Трансформатор мідь", tx_cu),
             ("Трансформатор ферит", tx_core), ("HV міст (4-кв., провідн.)", hv_cond),
             ("HV перемикальні+Qrr", hv_sw), ("Вихідний фільтр", filt),
             ("Конденсатори/шини/клеми", caps_bus), ("Драйвери/ESP/вентилятор", aux)]
    tot = sum(v for _, v in items)
    print(f"\n{label}  (n={n:.1f}, I_pri RMS={Irms:.0f} А, {4*m_lv} шт IRLB3034)")
    for k, v in items:
        print(f"    {k:<32s} {v:6.1f} Вт")
    print(f"    {'РАЗОМ':<32s} {tot:6.1f} Вт   ->  ККД = {P/(P+tot)*100:.2f}%")
    return tot

budget(20.0, 3, "A) 20 В (6s мінімум), 3 паралельно - як 'затверджено'")
