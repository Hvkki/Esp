"""
Перевірка розрахунків одноступеневого HF-link інвертора (DC->HF трансформатор->циклоконвертор)
Вхід: 6s Li-Ion 20..25 В, вихід 230 В RMS / 50 Гц, 3 кВт
Мета: перевірити цифри з переписки (125 А первинка, 15 Вт LV-міст, 7 Вт трансформатор, ККД 99%)
"""
import math

RHO_CU_20 = 1.72e-8      # Ом*м
ALPHA_CU = 0.00393
MU0 = 4 * math.pi * 1e-7

def rho_cu(T):
    return RHO_CU_20 * (1 + ALPHA_CU * (T - 20))

def skin_depth(f, T=100.0):
    return math.sqrt(rho_cu(T) / (math.pi * f * MU0))

def dowell_Fr(h, delta, m):
    """Коеф. збільшення опору за Dowell для фольги: h - товщина шару, m - к-ть шарів у секції"""
    D = h / delta
    a = D * (math.sinh(2*D) + math.sin(2*D)) / (math.cosh(2*D) - math.cos(2*D))
    b = (2.0/3.0) * D * (m*m - 1) * (math.sinh(D) - math.sin(D)) / (math.cosh(D) + math.cos(D))
    return a + b

def hr(title):
    print("\n" + "=" * 78)
    print(title)
    print("=" * 78)

# ---------------------------------------------------------------- 1. ВИХІД / СТРУМИ
hr("1. ВИХІД, МИТТЄВА ПОТУЖНІСТЬ, СТРУМИ (одноступенева схема БЕЗ HV DC-ланки)")

P = 3000.0
Vout_rms = 230.0
Vout_pk = Vout_rms * math.sqrt(2)
Iout_rms = P / Vout_rms
Iout_pk = Iout_rms * math.sqrt(2)

print(f"Pout = {P:.0f} Вт, Vout = {Vout_rms:.0f} В RMS -> Vpk = {Vout_pk:.1f} В  "
      f"(у переписці фігурує 315 В пік = {315/math.sqrt(2):.0f} В RMS - це вже не 230 В!)")
print(f"Iout: RMS = {Iout_rms:.2f} А, пік = {Iout_pk:.2f} А")
print()
print("КЛЮЧОВЕ: у схемі немає HV електролітичної/плівкової DC-ланки, тому вся миттєва")
print("потужність синуса p(t)=2*P*sin^2(wt) мусить пройти через LV-міст і трансформатор:")
print(f"  p_max = 2*P = {2*P:.0f} Вт  <-- залізо треба на 6 кВт піку, а не на 3 кВт")

for Vbat in (20.0, 24.0, 48.0):
    i_avg = P / Vbat
    i_rms = (P / Vbat) * math.sqrt(1.5)      # (1-cos2wt) форма
    i_pk = 2 * P / Vbat
    print(f"  Vbat={Vbat:>4.0f} В: I_bat avg={i_avg:6.1f} А  RMS={i_rms:6.1f} А  пік={i_pk:6.1f} А")

# ---------------------------------------------------------------- 2. КОЕФ. ТРАНСФОРМАЦІЇ
hr("2. КОЕФІЦІЄНТ ТРАНСФОРМАЦІЇ І СТРУМ ПЕРВИНКИ")

def design(Vbat, d_max=0.90, n=None):
    """d_max - максимальний duty на піку синуса (запас на мертвий час + duty loss)"""
    if n is None:
        n = Vout_pk / (Vbat * d_max)
    d_max_real = Vout_pk / (Vbat * n)
    Ipri_pk = n * Iout_pk
    # duty d(th) = d_max*sin(th); струм у первинці під час провідності = n*Iout_pk*sin(th)
    # I_rms^2 = <d(th) * (n*Iout_pk*sin th)^2> = (n*Iout_pk)^2 * d_max * <sin^3>
    mean_sin3 = 4.0 / (3.0 * math.pi)
    Ipri_rms = Ipri_pk * math.sqrt(d_max_real * mean_sin3)
    Isec_rms = Iout_pk * math.sqrt(d_max_real * mean_sin3)
    return n, d_max_real, Ipri_pk, Ipri_rms, Isec_rms

print("Потрібне n = Vout_pk/(Vbat*d_max).  Перевірка твердження 'n=16 при 20 В':")
n16_d = Vout_pk / (20.0 * 16.0)
print(f"  n=16, Vbat=20 В -> потрібний duty = {n16_d:.3f}  ->  {'НЕМОЖЛИВО (>1)' if n16_d>1 else 'ок'}")
print("  тобто вже на цьому кроці 16 витків вторинки при 1 витку первинки не дають 230 В RMS")
print()
for Vbat in (20.0, 24.0, 48.0):
    n, d, Ipk, Irms, Isec = design(Vbat)
    print(f"  Vbat={Vbat:>4.0f} В -> n={n:5.1f} (вторинка при Np=1)  d_max={d:.2f}  "
          f"I_pri пік={Ipk:6.1f} А  RMS={Irms:6.1f} А   I_sec RMS={Isec:5.1f} А")

print()
print("У переписці всюди фігурує 125 А по первинці. Реально:")
n20, d20, Ipk20, Irms20, Isec20 = design(20.0)
print(f"  пік {Ipk20:.0f} А ({Ipk20/125:.1f}x більше), RMS {Irms20:.0f} А ({Irms20/125:.1f}x).")
print(f"  Втрати I^2*R => недооцінка у {(Irms20/125)**2:.1f} рази.")

# ---------------------------------------------------------------- 3. LV МІСТ
