"""
САМОАУДИТ. Перепроверка моїх власних розрахунків з даними, підтвердженими по даталистах.
Джерела (перевірено пошуком):
  IRLB3034PbF : 40 В, Id=195 А (package limited), Rds(on) max 1.7 мОм @195А/10В,
                Ciss 10315 пФ, Pd 375 Вт, Qg 162 нК @Vgs=4.5 В
  IPW65R019C7 : 650 В, 19 мОм, CoolMOS C7, TO-247. Серії "IPW65R019CFD7" НЕ ІСНУЄ.
                CFD7 у TO-247 починається з ~35 мОм (IPW65R035CFD7A), далі 50/99/125/145/190 мОм.
  ETD59/31/22 N87 (B66397G0000X187): втрати сердечника <= 5.2 Вт/набір @100 мТл,100 кГц,100°C
                гапований B66397G1000X187: AL = 508 нГн; G2000: AL = 311 нГн
"""
import math

RHO20, ALPHA, MU0 = 1.72e-8, 0.00393, 4*math.pi*1e-7
rho = lambda T: RHO20*(1+ALPHA*(T-20))
delta = lambda f, T=100: math.sqrt(rho(T)/(math.pi*f*MU0))
def dowell(h, d, m):
    D = h/d
    return (D*(math.sinh(2*D)+math.sin(2*D))/(math.cosh(2*D)-math.cos(2*D))
            + (2/3)*D*(m*m-1)*(math.sinh(D)-math.sin(D))/(math.cosh(D)+math.cos(D)))
def hr(t): print("\n"+"="*80+"\n"+t+"\n"+"="*80)

# ---------------------------------------------------------------- 0. САМОПЕРЕВІРКА ФОРМУЛ
hr("0. ПЕРЕВІРКА МОЇХ ФОРМУЛ НА ГРАНИЧНИХ ВИПАДКАХ (щоб не вірити собі на слово)")
ok = []
ok.append(("Dowell: m=1, h<<d  -> Fr->1", abs(dowell(1e-6, 1e-3, 1)-1) < 1e-3))
ok.append(("Dowell: m=1, h>>d  -> Fr->h/d", abs(dowell(10e-3, 1e-3, 1)/10 - 1) < 0.05))
ok.append(("delta(150k,20C) ~ 0.17 мм", abs(delta(150e3, 20)*1e3 - 0.17) < 0.01))
ok.append(("delta(150k,100C) ~ 0.195 мм", abs(delta(150e3, 100)*1e3 - 0.195) < 0.01))
# RMS форми: i(t)=Ipk*sin -> RMS=Ipk/sqrt2 ; i=Ipk*sin^2 -> RMS=Ipk*sqrt(3/8)
N = 400000
s1 = sum(math.sin(math.pi*(k+.5)/N)**2 for k in range(N))/N
s2 = sum(math.sin(math.pi*(k+.5)/N)**4 for k in range(N))/N
ok.append(("<sin^2>=0.5", abs(s1-0.5) < 1e-4))
ok.append(("<sin^4>=0.375", abs(s2-0.375) < 1e-4))
for name, res in ok:
    print(f"  [{'OK ' if res else 'FAIL'}] {name}")
assert all(r for _, r in ok), "формули не проходять самоперевірку"

# ---------------------------------------------------------------- 1. ВИХІДНІ ДАНІ
P, Vo = 3000.0, 230.0
Vpk, Io_rms = Vo*math.sqrt(2), P/Vo
Io_pk = Io_rms*math.sqrt(2)
f_c = 150e3

hr("1. ГОЛОВНА ПОМИЛКА В МОЇХ ПОПЕРЕДНІХ РОЗРАХУНКАХ: струм у первинці під час freewheel")
print("Я вважав, що поза інтервалом провідності струм первинки = 0. Це невірно для цієї схеми.")
print("У PSFB/HF-link з LC-фільтром на виході freewheel робить САМ випрямляч (обидва нижні")
print("ключі SR замкнені) -> вторинка закорочена -> струм первинки НЕ спадає, а циркулює")
print("через два ключі LV-моста. Це класичні 'circulating conduction losses' PSFB.")
print()
print("І тут є розвилка, яку треба свідомо вибрати:")
print("  ВАРІАНТ 1 (freewheel робить SR):  unfolder справді комутує лише 50 Гц (ТИ ПРАВИЙ),")
print("                                    але LV-міст має циркулюючий струм -> втрати вищі.")
print("  ВАРІАНТ 2 (freewheel робить unfolder): струм первинки щоцикла скидається в нуль,")
print("                                    -> unfolder комутує 150 кГц + проблема leakage.")
print()
for Vbat in (24.0, 48.0):
    n = Vpk/(Vbat*0.90)
    I_gated = n*Io_pk*math.sqrt(0.90*4/(3*math.pi))   # моя стара модель
    I_circ  = n*Io_rms                                # правильна для варіанту 1
    print(f"  Vbat={Vbat:.0f} В, n={n:4.1f}: I_pri RMS = {I_gated:5.1f} А (моя стара модель) "
          f"vs {I_circ:5.1f} А (варіант 1) -> втрати x{(I_circ/I_gated)**2:.2f}")

# ---------------------------------------------------------------- 2. КОМПОНЕНТИ
hr("2. ДАНІ КОМПОНЕНТІВ: ЩО ПІДТВЕРДИЛОСЬ, А ЩО НІ")
print("IRLB3034PbF - підтверджено: 40 В / 195 А (обмежено корпусом) / Rds(on) max 1.7 мОм.")
print("  Ciss = 10315 пФ (!). 12 шт паралельно = 124 нФ затворної ємності.")
print("  Драйвер мусить давати ~25 А піку, щоб перезарядити це за 50 нс.")
print()
print("ВАЖЛИВО: 40 В на 24 В шині. 6s Li-Ion повністю заряджений = 25.2 В.")
Lloop = 5e-9
for Ipk_leg, Vmax, Vrating, lbl in ((278.0, 25.2, 40, "24 В шина (6s max 25.2 В), IRLB3034 40 В"),
                                    (139.0, 54.6, 40, "48 В шина (13s max 54.6 В), IRLB3034 40 В"),
                                    (139.0, 54.6, 80, "48 В шина, ключ 80 В")):
    dv = Lloop*Ipk_leg/50e-9
    print(f"  {lbl}: комутація {Ipk_leg:.0f} А за 50 нс на петлі {Lloop*1e9:.0f} нГн -> "
          f"викид {dv:.0f} В поверх {Vmax:.1f} В = {Vmax+dv:.0f} В при межі {Vrating} В "
          f"-> {'ПРОБИТТЯ' if Vmax+dv > Vrating else 'ок (запас '+str(round((Vrating-Vmax-dv)/Vrating*100))+'%)'}")
print("  Тобто 40-вольтовий ключ на 24 В шині з такими струмами - без запасу.")
print("  Потрібні 60-80 В (OptiMOS/TOLL, напр. класу 0.7-1.5 мОм) або дуже жорсткий снабер.")
print()
print("IPW65R019CFD7 - ТАКОГО НОМЕРА НЕ ІСНУЄ. Це важливо:")
print("  * 19 мОм / 650 В = IPW65R019C7 (серія C7, ЗВИЧАЙНИЙ body diode).")
print("  * CFD7 (швидкий body diode, зроблена саме під LLC/PSFB) у TO-247 починається")
print("    з ~35 мОм (IPW65R035CFD7A), далі 50 / 99 / 125 / 145 / 190 мОм.")
print("  Наслідок: 19 мОм і 'швидкий діод' одночасно отримати не можна.")
print("  А для твого HV-каскаду поведінка body diode критична (жорстка комутація = Qrr).")

hr("3. HV-КАСКАД: ПЕРЕРАХУНОК ПІД РЕАЛЬНІ ДОСТУПНІ КЛЮЧІ")
print("Гарячий Rds(on): superjunction має x2.0-2.5 при Tj=100-125°C (типова крива CoolMOS).")
for name, rds25, kT in (("IPW65R019C7  (C7, звич. діод)", 0.019, 2.2),
                        ("IPW65R035CFD7A (швидкий діод)", 0.035, 2.2),
                        ("IPW65R050CFD7A", 0.050, 2.2),
                        ("2x IPW65R035CFD7A паралельно", 0.0175, 2.2)):
    rh = rds25*kT
    for ndev in (4,):
        print(f"  {name:<32s} гарячий {rh*1e3:5.1f} мОм -> {ndev} у шляху = "
              f"{Io_rms**2*ndev*rh:5.1f} Вт  ({Io_rms**2*ndev*rh/P*100:.2f}% ККД)")
print("  Моя попередня цифра 28 Вт була для 19 мОм. Для реального CFD7 35 мОм це вже 52 Вт.")

hr("4. ТРАНСФОРМАТОР: ВТРАТИ В ФЕРИТІ ПО ДАТАЛИСТУ, А НЕ ПО МОЄМУ ФІТУ")
Ae, Ve, MLT, bw, hw = 368e-6, 51.5e-6, 0.106, 38e-3, 9.5e-3
print(f"Даталист TDK B66397G0000X187 (ETD59/31/22, N87):")
print(f"  Pcore <= 5.2 Вт/набір при 100 мТл, 100 кГц, 100 °C  -> Pv = "
      f"{5.2/ (Ve*1e6) *1e3:.0f} мВт/см³")
print(f"  Мій попередній Steinmetz-фіт давав ~50 мВт/см³ -> Я ЗАНИЗИВ втрати фериту у ~2 рази.")
Pv_anchor = 5.2/(Ve*1e6)*1e3     # мВт/см³ при 100 мТл, 100 кГц
def core_loss(B_T, f, a=1.3, b=2.45):
    Pv = Pv_anchor*(f/100e3)**a*(B_T/0.1)**b
    return Pv*(Ve*1e6)/1e3
k_env = sum(math.sin(math.pi*(k+.5)/N)**2.45 for k in range(N))/N
print(f"  Коеф. усереднення по обвідній синуса (B~sin, показник 2.45): x{k_env:.2f}")
for Vbat in (24.0, 48.0):
    for Np in (1, 2):
        B = Vbat*0.9/(4*f_c*Np*Ae)
        print(f"  Vbat={Vbat:.0f}, Np={Np}: B={B*1e3:5.1f} мТл -> ферит "
              f"{core_loss(B,f_c)*k_env:4.1f} Вт (сер. по обвідній), "
              f"на піку {core_loss(B,f_c):4.1f} Вт")

print("\nЗАЗОР - тепер по даталисту, а не по моїй оцінці:")
for pn, AL in (("B66397G0000 (без зазору, оцінка µi)", 4700e-9),
               ("B66397G1000 (даталист)", 508e-9),
               ("B66397G2000 (даталист)", 311e-9)):
    L = AL*1**2
    dI = 24.0*(1/(2*f_c))/L
    print(f"  {pn:<38s} AL={AL*1e9:6.0f} нГн -> Np=1: L={L*1e6:5.2f} мкГн, "
          f"розмах I_магн = {dI:5.0f} А")
print("  Підтверджено: гапований сердечник при Np=1 - самогубство. Тільки без зазору.")

d = delta(f_c, 100)
print(f"\nМідь (delta={d*1e3:.3f} мм при 150 кГц/100°C):")
for Vbat in (24.0, 48.0):
    n = Vpk/(Vbat*0.90); Ns = round(n)
    I_pri = n*Io_rms                     # варіант 1, циркулюючий струм
    I_sec = Io_rms                       # вторинка теж несе струм і під час freewheel
    A_p = 0.2e-3*bw*4
    Rp = rho(100)*MLT/A_p; Frp = dowell(0.2e-3, d, 2)
    Pp = I_pri**2*Rp*Frp
    for A_s, lbl in ((5e-6, "літц 5 мм²"), (2.5e-6, "літц 2.5 мм²")):
        Rs = rho(100)*MLT*Ns/A_s; Ps = I_sec**2*Rs*1.15
        print(f"  Vbat={Vbat:.0f}: Np=1(4 шари пар.), Ns={Ns:2d}, {lbl:<14s} "
              f"перв={Pp:4.1f} Вт (Fr={Frp:.2f}, I={I_pri:.0f} А)  "
              f"втор={Ps:4.1f} Вт (I={I_sec:.1f} А)")
print("  Увага: вторинка тепер несе струм і під час freewheel -> її RMS = вихідний RMS,")
print("  а не 11.4 А, як я рахував раніше. Ще одна моя недооцінка.")

# ---------------------------------------------------------------- 5. НОВИЙ БЮДЖЕТ
hr("5. ПЕРЕПИСАНИЙ БЮДЖЕТ ВТРАТ (варіант 1, з циркулюючим струмом)")
def budget(Vbat, m_lv, rds_lv25, hv_rds25, hv_n, label, Np=1):
    n = Vpk/(Vbat*0.90); Ns = round(n*Np)
    I_pri = n*Io_rms
    lv = I_pri**2*2*(rds_lv25*1.5/m_lv)
    gate = 2*m_lv*2*200e-9*10*f_c
    lv_sw = 8.0
    A_p = 0.2e-3*bw*4
    cu_p = I_pri**2*(rho(100)*MLT*Np/A_p)*dowell(0.2e-3, d, 2)
    cu_s = Io_rms**2*(rho(100)*MLT*Ns/5e-6)*1.15
    B = Vbat*0.9/(4*f_c*Np*Ae); core = core_loss(B, f_c)*k_env
    hv = Io_rms**2*hv_n*hv_rds25*2.2
    hv_sw, filt, caps, aux = 15.0, 15.0, 10.0, 7.0
    items = [("LV міст (з циркулюючим струмом)", lv), ("LV затвори", gate),
             ("LV перемикальні", lv_sw), ("Транс: мідь первинки", cu_p),
             ("Транс: мідь вторинки", cu_s), ("Транс: ферит (даталист)", core),
             ("HV провідникові", hv), ("HV перемикальні + Qrr", hv_sw),
             ("Вихідний фільтр", filt), ("Конденсатори/шини/клеми", caps),
             ("Драйвери/ESP/вентилятор", aux)]
    tot = sum(v for _, v in items)
    print(f"\n{label}")
    for k, v in items: print(f"    {k:<36s} {v:6.1f} Вт")
    print(f"    {'РАЗОМ':<36s} {tot:6.1f} Вт   ККД = {P/(P+tot)*100:.2f}%")
    return tot

budget(24.0, 3, 0.0017, 0.019, 4, "A) 24 В, 12x IRLB3034, HV = IPW65R019C7 (оптимістично)")
budget(24.0, 3, 0.0017, 0.035, 4, "B) 24 В, 12x IRLB3034, HV = CFD7 35 мОм (реалістично)")
budget(48.0, 2, 0.0017, 0.0175, 4, "C) 48 В, Np=2, 8x IRLB3034(*), HV = 2x CFD7 35 мОм", Np=2)
budget(48.0, 3, 0.0009, 0.0175, 4, "D) 48 В, Np=2, 12x 80В/0.9мОм TOLL, HV = 2x CFD7", Np=2)
print("  (*) на 48 В IRLB3034 (40 В) непридатний за напругою - рядок C лише для порівняння R")

hr("6. СКІЛЬКИ ТРЕБА, ЩОБ ВИЙТИ НА 99% (30 Вт) - перевірка з новими числами")
for Vbat in (24.0, 48.0):
    n = Vpk/(Vbat*0.9); I_pri = n*Io_rms
    m10 = I_pri**2*2*0.00255/10
    print(f"  Vbat={Vbat:.0f} В: щоб LV-міст мав 10 Вт -> {m10:.0f} IRLB3034 на плече "
          f"({4*m10:.0f} на міст)")
print(f"  HV-каскад мінімум (19 мОм, 4 у шляху) = {Io_rms**2*4*0.019*2.2:.0f} Вт")
print(f"  Вже тільки LV(10)+HV(28)+фільтр(15)+транс(10) = 63 Вт = ККД 97.9% максимум.")
print("  Отже 99% при 3 кВт у цій топології недосяжні за жодної конфігурації. Це фізика.")

hr("7. ЩЕ ОДНА РІЧ, ЯКУ Я ПРОПУСТИВ: РЕАКТИВНЕ НАВАНТАЖЕННЯ")
print("Схема 'SR + unfolder' може тільки ВІДДАВАТИ енергію, не приймати.")
print("При реактивному навантаженні (двигун, трансформатор, ІБП, конденсаторний вхід БЖ)")
print("струм зсунутий по фазі: у момент нуля напруги струм НЕ нуль.")
for phi_deg in (0, 30, 60):
    phi = math.radians(phi_deg)
    print(f"  cos(phi)={math.cos(phi):.2f} (phi={phi_deg}°): струм у момент переходу напруги "
          f"через нуль = {abs(math.sin(phi))*100:.0f}% від піку = {Io_pk*abs(math.sin(phi)):.1f} А")
print("  Отже: unfolder мусить комутувати цей струм жорстко, І пропускати зворотний потік")
print("  енергії. Простий unfolder на 4 одиничних MOSFET цього не вміє -> перенапруга.")
print("  Для двигунів/частотника 20-400 Гц потрібні 4-квадрантні ключі + шлях для")
print("  реактивної енергії. Тобто 'частотник' - це вже інша, складніша машина.")
