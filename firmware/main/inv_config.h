// Значення за замовчуванням підібрані для БЕЗПЕЧНОГО ПЕРШОГО ЗАПУСКУ на лабораторному
// блоці живлення з обмеженням струму, а НЕ для роботи на 3 кВт від акумулятора.
// Зокрема INV_DUTY_MAX_Q15 обмежений на рівні ~12%. Підіймати його можна тільки після
// того, як на осцилографі підтверджено: правильні вікна SR, м'яка комутація, і працює
// АПАРАТНИЙ захист по струму.
#pragma once

// ---------------------------------------------------------------- силова частина
// LV ключі: IRL40SC209 (StrongIRFET, 40 В, D2PAK-7, Rds(on) max 1.3 мОм), ПАРНО в плечі.
//   D2PAK-7 має окремий Kelvin source - затворний контур ОБОВ'ЯЗКОВО замикати на нього,
//   інакше сенс цього корпусу втрачається.
//   Кожен MOSFET - свій затворний резистор 2...4 Ом (розподіл струму + проти коливань).
//   dv/dt на плечі досягає ~20 В/нс -> потрібне від'ємне зміщення затвора (-5 В)
//   і/або снабер на плече, інакше Miller-струм відкриває закритий ключ.
//   Тепловий шлях у D2PAK-7 іде через плату: IMS або 2 oz мідь + масив теплових вій.
#define INV_CARRIER_HZ            70000     // частота носія. Для першого прототипу 50-70 кГц.
#define INV_MCPWM_CLK_HZ          160000000 // тактова частота групи MCPWM (PLL_160M)
#define INV_PERIOD_TICKS          (INV_MCPWM_CLK_HZ / INV_CARRIER_HZ)   // 2286 при 70 кГц
#define INV_HALF_PERIOD_TICKS     (INV_PERIOD_TICKS / 2)

// Мертвий час LV-моста. Coss перезаряджається за одиниці наносекунд, тому довгий
// мертвий час = пряма втрата на body diode (див. docs/REVIEW.md, п.2.3).
// 60 нс при кроці 6.25 нс = 10 тіків.
#define INV_LV_DEADTIME_TICKS     10

// Мертвий час SR. Тут навпаки потрібен запас: помилкове увімкнення SR при зворотній
// напрузі = коротке через трансформатор.
#define INV_SR_DEADTIME_TICKS     16

// Затримки вікна SR відносно первинки (тіки). Підбираються по осцилографу.
// Позитивне значення = SR вмикається пізніше / вимикається раніше (консервативно).
#define INV_SR_LEAD_TICKS         8         // затримка увімкнення
#define INV_SR_TRAIL_TICKS        8         // випередження вимикання

// ---------------------------------------------------------------- модуляція
#define INV_OUT_FREQ_HZ_DEFAULT   50.0f
#define INV_OUT_FREQ_HZ_MIN       20.0f
#define INV_OUT_FREQ_HZ_MAX       400.0f

// Прорідження ISR модуляції: оновлюємо duty кожні N періодів носія.
// 70 кГц / 4 = 17.5 кГц -> 175 точок на півхвилю 50 Гц. Достатньо.
#define INV_MOD_DECIM             4

// Максимальний duty (Q15). 0.90 -> 29491. Для першого запуску 0.12 -> 3932.
#define INV_DUTY_MAX_Q15          3932

// Софт-старт: за скільки мілісекунд амплітуда підіймається від 0 до цілі.
#define INV_SOFTSTART_MS          500

// Блокування unfolder на переході полярності (мікросекунди).
#define INV_UNFOLDER_BLANK_US     150

// ---------------------------------------------------------------- розподіл MCPWM
// ESP32 / ESP32-S3: два блоки MCPWM, у кожному 3 таймери і 3 оператори (6 виходів).
// ESP32-S2 блоку MCPWM не має - цей код на S2 не збереться.
#define INV_LV_GROUP              0         // MCPWM0: LV H-міст (4 виходи)
#define INV_SR_GROUP              1         // MCPWM1: синхронний випрямляч (4 виходи)
// Unfolder працює на частоті виходу (20-400 Гц) - звичайні GPIO з ISR модуляції.

// ---------------------------------------------------------------- карта виводів
// LV H-міст, плече A (ведуче) і плече B (ведене, зі зсувом фази)
#define GPIO_LV_A_HI              4
#define GPIO_LV_A_LO              5
#define GPIO_LV_B_HI              6
#define GPIO_LV_B_LO              7

// Синхронний випрямляч (HV сторона, ізольовані драйвери!)
#define GPIO_SR_A_HI              15
#define GPIO_SR_A_LO              16
#define GPIO_SR_B_HI              17
#define GPIO_SR_B_LO              18

// Unfolder: два ключі на позитивну півхвилю, два на негативну
#define GPIO_UNF_POS              8
#define GPIO_UNF_NEG              9

// Апаратний захист: активний низький. Приходить з аналогового компаратора струму
// (шунт/CT -> компаратор -> цей вивід). ОБОВ'ЯЗКОВИЙ.
#define GPIO_FAULT_N              10
// Дозвіл драйверів. Поки низький - усі драйвери в shutdown.
#define GPIO_DRV_ENABLE           11
// Індикація
#define GPIO_LED_RUN              12
#define GPIO_LED_FAULT            13
